"""Render as TypeScript declarations."""

from __future__ import annotations

import json
import re

from ..schema import (
    Array,
    Boolean,
    DataSchema,
    Entity,
    Integer,
    Node,
    Null,
    Number,
    Object,
    String,
    Union,
    Unknown,
)
from .naming import pascal_case, unique

_INDENT = "  "
_PLAIN_KEY = re.compile(r"[A-Za-z_$][\w$]*")
_HEADER = "// Generated by DataNyx. Contains no data values."


def render_typescript(schema: DataSchema) -> str:
    used: set[str] = set()
    blocks = [_HEADER]
    for entity in schema.entities:
        blocks.append(_entity(entity, unique(pascal_case(entity.name), used)))
    return "\n\n".join(blocks)


def _entity(entity: Entity, name: str) -> str:
    comments = []
    if entity.name and pascal_case(entity.name) != entity.name:
        comments.append(f"// {entity.name}")
    if entity.primary_key:
        comments.append(f"// primary key: {', '.join(entity.primary_key)}")
    for key in entity.foreign_keys:
        columns, referenced = ", ".join(key.columns), ", ".join(key.referenced_columns)
        comments.append(f"// foreign key: {columns} -> {key.referenced_entity} ({referenced})")
    node = entity.node
    head = "\n".join(comments + [""])[:-1] if comments else ""
    prefix = head + "\n" if head else ""
    if isinstance(node, Object) and node.extra is None:
        return f"{prefix}export interface {name} {_object(node, 0)}"
    return f"{prefix}export type {name} = {_node(node, 0)};"


def _node(node: Node, depth: int) -> str:
    if isinstance(node, Unknown):
        return "unknown"
    if isinstance(node, Null):
        return "null"
    if isinstance(node, Boolean):
        return "boolean"
    if isinstance(node, (Integer, Number)):
        return "number"
    if isinstance(node, String):
        return f"string /* {node.format} */" if node.format else "string"
    if isinstance(node, Array):
        return f"Array<{_node(node.items, depth)}>"
    if isinstance(node, Union):
        return " | ".join(_node(option, depth) for option in node.options)
    if isinstance(node, Object):
        return _object(node, depth)
    raise TypeError(f"unhandled node: {type(node).__name__}")


def _object(node: Object, depth: int) -> str:
    extra = f"Record<string, {_node(node.extra, depth)}>" if node.extra is not None else None
    if not node.fields:
        return extra or "{}"
    pad = _INDENT * (depth + 1)
    lines = []
    for name, field in node.fields.items():
        key = name if _PLAIN_KEY.fullmatch(name) else json.dumps(name)
        marker = "" if field.required else "?"
        comment = f" // {field.native_type}" if field.native_type else ""
        lines.append(f"{pad}{key}{marker}: {_node(field.node, depth + 1)};{comment}")
    body = "{\n" + "\n".join(lines) + "\n" + _INDENT * depth + "}"
    return f"{body} & {extra}" if extra else body
