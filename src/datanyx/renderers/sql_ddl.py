"""Render as CREATE TABLE statements.

The types are portable guesses rather than any one dialect's, and a database's own
types are kept when a schema came from a database. Other sources' type names (Avro's
`union`, Stata's `%8.0g`) aren't SQL, so they stay out. Nested data becomes JSON.
"""

from __future__ import annotations

import re

from ..schema import (
    Array,
    Boolean,
    DataSchema,
    Entity,
    Field,
    Integer,
    Node,
    Null,
    Number,
    Object,
    String,
    Union,
    Unknown,
)

# Only what a type name needs: this text goes into SQL that may be run, and it can come from the input.
_SAFE_NATIVE_TYPE = re.compile(r"[A-Za-z_][\w .]*(\(\s*\w+(\s*,\s*\w+)*\s*\))?[\w \[\]]*")
_STRING_TYPES = {
    "date": "DATE",
    "date-time": "TIMESTAMP",
    "time": "TIME",
    "uuid": "UUID",
    "binary": "BLOB",
}


def render_sql_ddl(schema: DataSchema) -> str:
    native = schema.source_kind in _SQL_TYPED_SOURCES
    return "\n\n".join(["-- Generated by DataNyx. Contains no data values.", *(_table(entity, native) for entity in schema.entities)])


def _quote(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def _table(entity: Entity, native: bool) -> str:
    node = entity.node.items if isinstance(entity.node, Array) else entity.node
    name = _quote(entity.name or "root")
    if not isinstance(node, Object):
        return f"CREATE TABLE {name} (\n  \"value\" {_column_type(node)}\n);"

    lines = [_column(column, field, native) for column, field in node.fields.items()]
    if entity.primary_key:
        lines.append(f"PRIMARY KEY ({', '.join(map(_quote, entity.primary_key))})")
    guesses = []
    for key in entity.foreign_keys:
        target = f"{_quote(key.referenced_entity)} ({', '.join(map(_quote, key.referenced_columns))})"
        if key.inferred:  # A guess, so a comment rather than a constraint the database would enforce.
            guesses.append(f"-- inferred join (not enforced): ({', '.join(map(_quote, key.columns))}) -> {target}")
        else:
            lines.append(f"FOREIGN KEY ({', '.join(map(_quote, key.columns))}) REFERENCES {target}")
    unique = [column for column, field in node.fields.items() if field.unique]
    if unique:
        guesses.append(f"-- inferred unique (not enforced): {', '.join(map(_quote, unique))}")
    if entity.scale:
        guesses.append(f"-- about {entity.scale}")
    if not lines:
        lines.append('"value" JSON')  # A table needs a column; this stands for the unnamed keys.
    body = ",\n".join("  " + line for line in lines)
    comment = ""
    if node.extra is not None:
        comment = f"\n-- DataNyx hid some column names here; their values are {_describe(node.extra)}."
    comment += "".join("\n" + guess for guess in guesses)
    return f"CREATE TABLE {name} (\n{body}\n);{comment}"


def _column(name: str, field: Field, native: bool) -> str:
    node = field.node
    nullable = not field.required or _allows_null(node)
    native = field.native_type
    kind = native if native and _SAFE_NATIVE_TYPE.fullmatch(native) else _column_type(node)
    return f"{_quote(name)} {kind}" + ("" if nullable else " NOT NULL")


def _allows_null(node: Node) -> bool:
    return isinstance(node, Null) or (isinstance(node, Union) and any(isinstance(o, Null) for o in node.options))


def _column_type(node: Node) -> str:
    if isinstance(node, Union):
        options = [option for option in node.options if not isinstance(option, Null)]
        if len(options) == 1:
            return _column_type(options[0])
        if {type(option) for option in options} <= {Integer, Number}:
            return "DOUBLE PRECISION"
        return "JSON"  # Several kinds of value in one column.
    if isinstance(node, Boolean):
        return "BOOLEAN"
    if isinstance(node, Integer):
        return "INTEGER"
    if isinstance(node, Number):
        return "DOUBLE PRECISION"
    if isinstance(node, String):
        return _STRING_TYPES.get(node.format or "", "TEXT")
    if isinstance(node, (Array, Object)):
        return "JSON"
    if isinstance(node, (Unknown, Null)):
        return "TEXT"
    raise TypeError(f"unhandled node: {type(node).__name__}")


def _describe(node: Node) -> str:
    return _column_type(node)
