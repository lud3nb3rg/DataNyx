"""Render as Pydantic v2 models (Python source)."""

from __future__ import annotations

from ..schema import (
    Array,
    Boolean,
    DataSchema,
    Entity,
    Integer,
    Node,
    Null,
    Number,
    Object,
    String,
    Union,
    Unknown,
)
from .naming import pascal_case, python_field_name, unique

_FORMAT_TYPES = {
    "date": "_dt.date",
    "date-time": "_dt.datetime",
    "time": "_dt.time",
    "uuid": "_uuid.UUID",
    "ipv4": "_ip.IPv4Address",
    "ipv6": "_ip.IPv6Address",
    "binary": "bytes",
}
_HEADER = '''# Generated by DataNyx. Contains no data values.
from __future__ import annotations

import datetime as _dt
import ipaddress as _ip
import typing as _t
import uuid as _uuid

from pydantic import BaseModel, ConfigDict, Field'''


def render_pydantic(schema: DataSchema) -> str:
    builder = _Builder()
    aliases: list[str] = []
    for entity in schema.entities:
        aliases.extend(builder.entity(entity))
    return "\n\n\n".join([_HEADER, *builder.classes, *aliases]) + "\n"


class _Builder:
    def __init__(self) -> None:
        self.classes: list[str] = []
        self._used: set[str] = set()

    def entity(self, entity: Entity) -> list[str]:
        """Add the entity's classes; return any alias that must follow them."""
        name = unique(pascal_case(entity.name), self._used)
        node = entity.node
        if isinstance(node, Object) and (node.extra is None or node.fields):
            self._class(node, name, entity)
            return []
        return [f"{name} = {self._type(node, name)}"]

    def _type(self, node: Node, hint: str) -> str:
        if isinstance(node, Unknown):
            return "_t.Any"
        if isinstance(node, Null):
            return "None"
        if isinstance(node, Boolean):
            return "bool"
        if isinstance(node, Integer):
            return "int"
        if isinstance(node, Number):
            return "float"
        if isinstance(node, String):
            return _FORMAT_TYPES.get(node.format or "", "str")
        if isinstance(node, Array):
            return f"list[{self._type(node.items, hint + 'Item')}]"
        if isinstance(node, Union):
            options = [self._type(option, hint) for option in node.options]
            return " | ".join(dict.fromkeys(options))
        if isinstance(node, Object):
            if not node.fields:
                value = self._type(node.extra, hint + "Value") if node.extra is not None else "_t.Any"
                return f"dict[str, {value}]"
            return self._class(node, unique(hint, self._used), None)
        raise TypeError(f"unhandled node: {type(node).__name__}")

    def _class(self, node: Object, name: str, entity: Entity | None) -> str:
        lines: list[str] = []
        taken: set[str] = set()
        renamed = False
        for original, field in node.fields.items():
            attribute = unique(python_field_name(original), taken)
            annotation = self._type(field.node, name + pascal_case(original, "Field"))
            has_null = _allows_null(field.node)
            if not field.required:
                annotation = annotation if has_null else f"{annotation} | None"
            if attribute != original:
                renamed = True
                arguments = ["default=None, " if not field.required else "", f"alias={original!r}"]
                default = f" = Field({''.join(arguments)})"
            else:
                default = "" if field.required else " = None"
            lines.append(f"    {attribute}: {annotation}{default}")

        settings = []
        if node.extra is not None:
            settings.append('extra="allow"')
        if renamed:
            settings.append("populate_by_name=True")
        docs = [f"    # Other keys are allowed: {self._type(node.extra, name + 'Value')}"] if node.extra else []
        if entity is not None and entity.primary_key:
            docs.append(f"    # primary key: {', '.join(entity.primary_key)}")
        if entity is not None:
            for key in entity.foreign_keys:
                docs.append(
                    f"    # foreign key: {', '.join(key.columns)} -> "
                    f"{key.referenced_entity} ({', '.join(key.referenced_columns)})"
                )
        if settings:
            lines.insert(0, f"    model_config = ConfigDict({', '.join(settings)})")
        body = docs + lines or ["    pass"]
        self.classes.append(f"class {name}(BaseModel):\n" + "\n".join(body))
        return name


def _allows_null(node: Node) -> bool:
    return isinstance(node, Null) or (isinstance(node, Union) and any(isinstance(o, Null) for o in node.options))
