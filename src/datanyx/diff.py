"""Compare two schemas: what was added, removed or changed, and what could break.

For a data feed that code depends on: save a schema today (`datanyx schema feed.csv -o
schema.json`), and later compare it with the feed as it is then. Either side of a comparison
can be such a saved schema or any input DataNyx reads.

Changes are sorted by what they mean for code written against the old schema:

- breaking: it may stop working. A field is gone, a type widened (a number may now be text, a
  field may now be null), a format was lost, or a field that was always there is now optional.
- compatible: old code still works. A field was added, a type narrowed, a field is now required.
- info: worth knowing, but not a break: a database type changed, keys were added or removed.

Only names and types are compared, and they are the names a schema already shows, so the
result reveals nothing a schema doesn't.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from .privacy import KeyPolicy

BREAKING, COMPATIBLE, INFO = "breaking", "compatible", "info"
_ORDER = (BREAKING, COMPATIBLE, INFO)
_SYMBOLS = {"added": "+", "removed": "-", "changed": "~"}
_MAX_SNAPSHOT_BYTES = 5_000_000


@dataclass(frozen=True)
class Difference:
    severity: str
    kind: str  # added, removed or changed
    path: str
    message: str

    def as_dict(self) -> dict[str, str]:
        return {"severity": self.severity, "kind": self.kind, "path": self.path, "message": self.message}


# --- loading ------------------------------------------------------------------------------


def snapshot(
    target: str,
    policy: KeyPolicy | None = None,
    source: str | None = None,
    namespace: str | None = None,
    recursive: bool = False,
) -> dict[str, Any]:
    """A schema as a JSON Schema document: a saved one read as it is, anything else extracted."""
    saved = _read_saved(target)
    if saved is not None:
        return saved
    from . import extract, render

    return json.loads(render(extract(target, source, policy or KeyPolicy(), namespace, recursive), "json-schema"))


def _read_saved(target: str) -> dict[str, Any] | None:
    if not target.lower().endswith(".json") or not os.path.isfile(target) or os.path.getsize(target) > _MAX_SNAPSHOT_BYTES:
        return None
    try:
        data = json.loads(Path(target).read_text(encoding="utf-8-sig"))
    except (OSError, ValueError):
        return None
    comment = data.get("$comment") if isinstance(data, dict) else None
    if isinstance(comment, str) and "Generated by DataNyx" in comment and "$schema" in data:
        return data
    return None


def _entities(document: dict[str, Any]) -> dict[str, tuple[str, dict[str, Any]]]:
    """Entity name -> (the path its fields start from, its schema)."""
    if "$defs" in document:
        return {name: (name, schema) for name, schema in document["$defs"].items()}
    body = {key: value for key, value in document.items() if key not in ("$schema", "$comment")}
    return {"(the document)": ("$", body)}


# --- comparing ----------------------------------------------------------------------------


def diff_schemas(old: dict[str, Any], new: dict[str, Any]) -> list[Difference]:
    """Every difference between two JSON Schema documents made by DataNyx."""
    found: list[Difference] = []
    before, after = _entities(old), _entities(new)
    for name in before.keys() - after.keys():
        found.append(Difference(BREAKING, "removed", before[name][0], "removed"))
    for name in after.keys() - before.keys():
        found.append(Difference(COMPATIBLE, "added", after[name][0], "added"))
    for name in before.keys() & after.keys():
        path, old_schema = before[name]
        _compare(old_schema, after[name][1], path, found)
        _compare_keys(old_schema, after[name][1], path, found)
    return sorted(found, key=lambda d: (_ORDER.index(d.severity), d.path, d.kind))


def _branches(schema: dict[str, Any]) -> dict[str, dict[str, Any]]:
    """The kinds of value a schema allows, each with the part of the schema that describes it."""
    if not schema:
        return {"unknown": {}}
    if "anyOf" in schema:
        merged: dict[str, dict[str, Any]] = {}
        for option in schema["anyOf"]:
            merged.update(_branches(option))
        return merged
    kind = schema.get("type")
    if isinstance(kind, list):
        return {k: ({"type": k, "format": schema["format"]} if k == "string" and "format" in schema else {"type": k}) for k in kind}
    return {kind or "unknown": schema}


def _allows(kinds: dict[str, Any] | set[str], kind: str) -> bool:
    return kind in kinds or (kind == "integer" and "number" in kinds)


def _label(branches: dict[str, dict[str, Any]]) -> str:
    parts = []
    for kind in sorted(branches, key=lambda k: (k == "null", k)):
        fmt = branches[kind].get("format")
        parts.append(f"{kind}<{fmt}>" if fmt else kind)
    return " | ".join(parts)


def _compare(old: dict[str, Any], new: dict[str, Any], path: str, found: list[Difference]) -> None:
    before, after = _branches(old), _branches(new)
    if "unknown" in before or "unknown" in after:
        if ("unknown" in before) != ("unknown" in after):
            found.append(Difference(INFO, "changed", path, f"{_label(before)} -> {_label(after)}"))
        return

    widened = {kind for kind in after if not _allows(before, kind)}
    narrowed = {kind for kind in before if not _allows(after, kind)}
    if widened or narrowed:
        if widened == {"null"} and not narrowed:
            note = "can now be null"
        elif narrowed == {"null"} and not widened:
            note = "can no longer be null"
        elif widened:
            note = "now also " + ", ".join(sorted(widened))
        else:
            note = "no longer " + ", ".join(sorted(narrowed))
        severity = BREAKING if widened else COMPATIBLE
        found.append(Difference(severity, "changed", path, f"{_label(before)} -> {_label(after)}  ({note})"))

    for kind in before.keys() & after.keys():
        if kind == "string":
            _compare_format(before[kind], after[kind], path, found)
        elif kind == "object":
            _compare_object(before[kind], after[kind], path, found)
        elif kind == "array":
            _compare(before[kind].get("items", {}), after[kind].get("items", {}), path + "[]", found)


def _compare_format(old: dict[str, Any], new: dict[str, Any], path: str, found: list[Difference]) -> None:
    before, after = old.get("format"), new.get("format")
    if before == after:
        return
    if after is None:
        found.append(Difference(BREAKING, "changed", path, f"format <{before}> lost: values are no longer all {before}"))
    elif before is None:
        found.append(Difference(COMPATIBLE, "changed", path, f"values are now all <{after}>"))
    else:
        found.append(Difference(BREAKING, "changed", path, f"format <{before}> -> <{after}>"))


def _compare_object(old: dict[str, Any], new: dict[str, Any], path: str, found: list[Difference]) -> None:
    before, after = old.get("properties", {}), new.get("properties", {})
    required_before, required_after = set(old.get("required", [])), set(new.get("required", []))
    for key in sorted(before.keys() - after.keys()):
        found.append(Difference(BREAKING, "removed", f"{path}.{key}", "removed"))
    for key in sorted(after.keys() - before.keys()):
        needed = "required" if key in required_after else "optional"
        found.append(Difference(COMPATIBLE, "added", f"{path}.{key}", f"added  ({_label(_branches(after[key]))}, {needed})"))
    for key in sorted(before.keys() & after.keys()):
        here = f"{path}.{key}"
        if key in required_before and key not in required_after:
            found.append(Difference(BREAKING, "changed", here, "was always present, now optional"))
        elif key in required_after and key not in required_before:
            found.append(Difference(COMPATIBLE, "changed", here, "optional -> always present"))
        _compare(before[key], after[key], here, found)
        native_before, native_after = before[key].get("x-native-type"), after[key].get("x-native-type")
        if native_before != native_after:
            found.append(Difference(INFO, "changed", here, f"database type {native_before or 'none'} -> {native_after or 'none'}"))

    map_before, map_after = old.get("additionalProperties"), new.get("additionalProperties")
    if map_before is not None and map_after is not None:
        _compare(map_before, map_after, f"{path}.*", found)
    elif map_before is not None or map_after is not None:
        gained = map_after is not None
        found.append(
            Difference(INFO, "changed", path, "some key names are now hidden" if gained else "no key names are hidden any more")
        )


def _compare_keys(old: dict[str, Any], new: dict[str, Any], path: str, found: list[Difference]) -> None:
    for label, key in (("primary key", "x-primary-key"), ("foreign keys", "x-foreign-keys")):
        if old.get(key) != new.get(key):
            found.append(Difference(INFO, "changed", path, f"{label} changed: {_keys(old.get(key))} -> {_keys(new.get(key))}"))


def _keys(value: Any) -> str:
    if not value:
        return "none"
    if isinstance(value, list) and all(isinstance(item, str) for item in value):
        return "(" + ", ".join(value) + ")"
    return "; ".join(
        f"({', '.join(item['columns'])}) -> {item['references']['table']}" for item in value if isinstance(item, dict)
    )


# --- output -------------------------------------------------------------------------------


def render_diff(differences: list[Difference], output_format: str = "text") -> str:
    if output_format == "json":
        return json.dumps([item.as_dict() for item in differences], indent=2)
    if not differences:
        return "No differences."
    counts = {severity: sum(d.severity == severity for d in differences) for severity in _ORDER}
    lines = [", ".join(f"{count} {severity}" for severity, count in counts.items() if count)]
    for severity in _ORDER:
        group = [d for d in differences if d.severity == severity]
        if group:
            lines += ["", f"{severity}:"]
            lines += [f"  {_SYMBOLS[d.kind]} {d.path}: {d.message}" for d in group]
    return chr(10).join(lines)


def has_breaking(differences: list[Difference]) -> bool:
    return any(d.severity == BREAKING for d in differences)


__all__ = ["BREAKING", "COMPATIBLE", "INFO", "Difference", "diff_schemas", "has_breaking", "render_diff", "snapshot"]
