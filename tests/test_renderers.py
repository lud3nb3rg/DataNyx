"""Generated TypeScript, Pydantic and SQL must be valid and must carry no values."""

import json
import sqlite3
import sys
import types

import pytest

from datanyx import extract, render

CANARY = "zq-canary-value"
DOCUMENT = [
    {"id": 1, "email": "a@x.com", "tags": ["a"], "meta": {"k": 1.5, "when": "2024-01-02"}, "class": None, "n": CANARY},
    {"id": 2, "email": "b@x.com", "class": "x", "n": "y", "ts": "2024-01-02T03:04:05Z"},
    {"id": 3, "email": "c@x.com", "class": "z", "n": "y", "jane.doe@example.com": True},
]


def load(source, name="generated_models"):
    """Import generated code as a module, which is how Pydantic expects to find its types."""
    module = types.ModuleType(name)
    sys.modules[name] = module
    exec(compile(source, name, "exec"), module.__dict__)
    return module.__dict__


@pytest.fixture
def document(tmp_path):
    path = tmp_path / "d.json"
    path.write_text(json.dumps(DOCUMENT), encoding="utf-8")
    return str(path)


@pytest.mark.parametrize("name", ["typescript", "pydantic", "sql"])
def test_no_values_or_hidden_names(document, name):
    output = render(extract(document), name)
    assert CANARY not in output and "jane.doe" not in output and "Generated by DataNyx" in output


def test_typescript(document):
    output = render(extract(document), "typescript")
    assert "export type Root = Array<{" in output
    assert "id: number;" in output
    assert "tags?: Array<string>;" in output
    assert "class: string | null;" in output
    assert "} & Record<string, boolean>>;" in output


def test_pydantic_code_runs_and_validates(document):
    pytest.importorskip("pydantic")
    namespace = load(render(extract(document), "pydantic"))
    row = namespace["RootItem"].model_validate(DOCUMENT[0] | {"jane.doe@example.com": True})
    assert row.class_ is None and row.meta.k == 1.5
    namespace["RootItem"].model_validate(DOCUMENT[1])
    with pytest.raises(Exception):
        namespace["RootItem"].model_validate({"id": "not a number"})


def test_pydantic_awkward_names(tmp_path):
    pytest.importorskip("pydantic")
    path = tmp_path / "d.json"
    path.write_text(json.dumps({"_private": 1, "model_x": 2, "from": 3, "1st": 4, "copy": 5}), encoding="utf-8")
    namespace = load(render(extract(str(path)), "pydantic"), "generated_awkward")
    model = namespace["Root"].model_validate({"_private": 1, "model_x": 2, "from": 3, "1st": 4, "copy": 5})
    assert model.model_dump(by_alias=True) == {"_private": 1, "model_x": 2, "from": 3, "1st": 4, "copy": 5}


def test_sql_is_valid_and_keeps_keys(tmp_path):
    source = tmp_path / "shop.db"
    connection = sqlite3.connect(source)
    connection.executescript(
        'create table items (id integer primary key, name varchar(20) not null);'
        "create table lines (item_id integer references items(id), qty integer);"
    )
    connection.close()
    ddl = render(extract(str(source)), "sql")
    fresh = sqlite3.connect(":memory:")
    fresh.executescript(ddl)
    info = fresh.execute('pragma table_info("items")').fetchall()
    assert [(row[1], row[3]) for row in info] == [("id", 1), ("name", 1)]
    assert fresh.execute('pragma foreign_key_list("lines")').fetchall()[0][2] == "items"


def test_sql_from_a_json_document_runs(document):
    ddl = render(extract(document), "sql")
    sqlite3.connect(":memory:").executescript(ddl)
    assert '"id" INTEGER NOT NULL' in ddl and '"tags" JSON' in ddl


def test_folder_schema_renders_in_every_format(tmp_path):
    folder = tmp_path / "d"
    folder.mkdir()
    (folder / "orders.csv").write_text("id,user_id\n1,2\n", encoding="utf-8")
    (folder / "users.json").write_text('[{"user_id": 2}]', encoding="utf-8")
    schema = extract(str(folder))
    for name in ("json-schema", "text", "typescript", "pydantic", "sql"):
        assert render(schema, name)
    sqlite3.connect(":memory:").executescript(render(schema, "sql"))
    if pytest.importorskip("pydantic"):
        load(render(schema, "pydantic"), "generated_folder")
